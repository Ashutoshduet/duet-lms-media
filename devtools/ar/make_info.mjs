// Writes ar/info.json: what DUET AR says when a Human Body part is tapped, taken from the Human Body app's own words
// (body/js/data.js names and jobs, body/models/content.json names, jobs and the list of recorded clips, in English,
// Hindi and Hinglish). Only the parts of the models in ar/catalog.json are kept, so the file stays small.
// Usage: node devtools/ar/make_info.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const ROOT = new URL('../../', import.meta.url).pathname;
const { PARTS } = await import(ROOT + 'body/js/data.js');
const content = JSON.parse(readFileSync(ROOT + 'body/models/content.json', 'utf8'));
const cat = JSON.parse(readFileSync(ROOT + 'ar/catalog.json', 'utf8'));
// the Human Body app's mesh-group → part names (body/js/content.js GROUP_ALIAS), plus a few for the whole-body model
const ALIAS = {
  heart_ra: 'right_atrium', heart_rv: 'right_ventricle', heart_la: 'left_atrium', heart_lv: 'left_ventricle',
  valve_tricuspid: 'tricuspid_valve', valve_mitral: 'mitral_valve', valve_pulmonary: 'pulmonary_valve', valve_aortic: 'aortic_valve',
  papillary: 'papillary_muscles', kidney_l: 'kidneys', kidney_r: 'kidneys', pulm_arteries: 'pulmonary_arteries', pulm_veins: 'pulmonary_veins',
  coronary: 'coronary_arteries', adrenal: 'adrenal_glands', thyroid: 'thyroid_gland', bile_ducts: 'bile_duct', eyes: 'eye',
  arteries_minor: 'arteries', veins_minor: 'veins', nerves_minor: 'nerves', brain_deep: 'basal_ganglia',
};
const names = {};
for (const [id, v] of Object.entries(PARTS)) names[id] = { name: { en: v[0], hi: v[1] }, job: { en: v[2], hi: v[3] } };
for (const [id, v] of Object.entries(content.parts || {})) names[id] = { name: { ...(names[id] || {}).name, ...v.name }, job: { ...(names[id] || {}).job, ...v.job } };
const resolve = (n) => (names[n] ? n : ALIAS[n] && names[ALIAS[n]] ? ALIAS[n] : null);

// every mesh name of every body model the catalog uses
function meshNames(file) {
  const b = readFileSync(file), l = b.readUInt32LE(12), j = JSON.parse(b.subarray(20, 20 + l).toString());
  return (j.nodes || []).filter((n) => n.mesh != null).map((n) => n.name.replace(/_\d+$/, ''));
}
const parts = {}, mesh = {}, missing = new Set();
for (const it of cat.items) {
  if (!it.parts || !it.src || it.parts === 'proc') continue;
  for (const n of meshNames(ROOT + 'ar/' + it.src)) {
    const id = resolve(n); if (!id) { missing.add(n); continue; }
    if (id !== n) mesh[n] = id;
    if (parts[id]) continue;
    const p = names[id], au = content.audio['part-' + id] || [];
    const langs = ['en', 'hi', 'hg'].filter((L) => au.includes(L) && existsSync(`${ROOT}body/audio/${L}/part-${id}.mp3`));
    parts[id] = { name: p.name, job: p.job, clip: langs };
  }
}
// the narration clips the cards play (body:<id>): their title and words, to show while they play
const steps = {};
for (const it of cat.items) {
  if (!it.say || !it.say.startsWith('body:')) continue;
  const k = it.say.slice(5), s = content.steps[k]; if (!s) { console.log('no step', k); continue; }
  steps[k] = { title: s.title, text: s.text, clip: ['en', 'hi', 'hg'].filter((L) => existsSync(`${ROOT}body/audio/${L}/${k}.mp3`)) };
}
const out = { v: 1, note: 'Generated by devtools/ar/make_info.mjs from the Human Body app (body/js/data.js, body/models/content.json). Do not edit.', mesh, parts, steps };
writeFileSync(ROOT + 'ar/info.json', JSON.stringify(out));
console.log('parts', Object.keys(parts).length, 'aliases', Object.keys(mesh).length, 'steps', Object.keys(steps).length, 'no name for', [...missing].join(' ') || '-',
  'clips', Object.values(parts).reduce((s, p) => s + p.clip.length, 0), 'size', JSON.stringify(out).length);

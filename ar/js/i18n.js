export function getLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && LANGS.some(([k]) => k === q)) return q;
  try { const s = localStorage.getItem('duet-ar-lang'); if (s) return s; } catch (e) { /* no storage */ }
  return (navigator.language || '').startsWith('hi') ? 'hi' : 'en';
}
export function setLang(l) { try { localStorage.setItem('duet-ar-lang', l); } catch (e) { /* no storage */ } }
